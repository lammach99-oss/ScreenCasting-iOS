import SwiftUI
import UIKit
import UniformTypeIdentifiers

@MainActor
final class RemoteClipboardPasteboard: ObservableObject {
    typealias Wire = RemoteClipboardProtocol
    typealias Grant = RemoteClipboardAuthority.Grant

    private struct Representation {
        let identifier: String
        let format: Wire.Format
        let formats: UInt8
    }

    struct ReadSource {
        let changeCount: () -> Int
        let itemCount: () -> Int
        let types: () -> [String]
        let providers: () -> [NSItemProvider]
    }

    static let originType = "app.screencasting.clipboard-origin"
    private static let blockedTypes: Set<String> = [
        "org.nspasteboard.concealedtype", "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype", "com.agilebits.onepassword",
        "excludeclipboardcontentfrommonitorprocessing", "clipboard viewer ignore",
        "canincludeinclipboardhistory", "canuploadtocloudclipboard"
    ]

    @Published private(set) var supported = false
    @Published private(set) var canSend = false
    @Published private(set) var reason: Wire.Reason = .ok
    @Published private(set) var automatic = false
    @Published private(set) var transferNotice: String?

    private let authority: RemoteClipboardAuthority
    private let worker: RemoteClipboardContentWorker
    private let send: (Grant, Int, RemoteClipboardContent, Bool) -> Void
    private let changed: (Grant, Int) -> Void
    private let readSource: ReadSource
    private var focus: (owner: RemoteClipboardFocus, slot: SlotOrdinal)?
    private var inboundRevision: (prefix: Wire.Prefix, epoch: UInt64)?
    private var grantFocusEpoch: UInt64?

    func bindFocus(_ owner: RemoteClipboardFocus, slot: SlotOrdinal) {
        focus = (owner, slot)
        owner.bind(self, slot: slot)
        resetFocus()
    }

    func resetFocus() {
        update(supported: supported, grant: nil, reason: .ok)
        ownWritePending = false
        ownRevision = nil
        inboundRevision = nil
        grantFocusEpoch = nil
        if let focus, let epoch = focus.owner.epoch, focus.owner.isAuthorized(slot: focus.slot, epoch: epoch) {
            lastCount = readSource.changeCount()
        }
    }

    private func focusAllows(_ epoch: UInt64?) -> Bool {
        guard let focus else { return true }
        guard let epoch else { return false }
        return focus.owner.isAuthorized(slot: focus.slot, epoch: epoch)
    }

    private var grant: Grant?
    private var pollTask: Task<Void, Never>?
    private var progress: Progress?
    private var reading = false
    private var readID = UUID()
    private var lastCount = 0
    private var pendingAutomaticRevision: Int?
    private var ownWritePending = false
    private var ownRevision: Int?

    init(authority: RemoteClipboardAuthority, worker: RemoteClipboardContentWorker,
         send: @escaping (Grant, Int, RemoteClipboardContent, Bool) -> Void,
         changed: @escaping (Grant, Int) -> Void, readSource: ReadSource? = nil) {
        self.authority = authority
        self.worker = worker
        self.send = send
        self.changed = changed
        self.readSource = readSource ?? ReadSource(changeCount: { Self.board.changeCount },
            itemCount: { Self.board.numberOfItems }, types: { Self.types(on: Self.board) },
            providers: { Self.board.itemProviders })
    }

    func update(supported: Bool, grant: Grant?, reason: Wire.Reason) {
        if self.supported != supported { self.supported = supported }
        if self.reason != reason { self.reason = reason }
        if !supported { automatic = false }
        let epoch = focus?.owner.epoch
        let current = (focusAllows(epoch) ? grant : nil).flatMap { value in
            authority.allows(value, direction: 1) || authority.allows(value, direction: 2) ? value : nil
        }
        guard self.grant != current else { return }
        self.grant = current
        grantFocusEpoch = epoch
        canSend = current.map { $0.directions & 1 != 0 } ?? false
        transferNotice = nil
        pendingAutomaticRevision = nil
        stopReading()
        pollTask?.cancel()
        pollTask = nil
        guard let current else { return }
        // A new grant always baselines metadata. No copy made outside the grant is replayed.
        lastCount = readSource.changeCount()
        pollTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 150_000_000)
                guard !Task.isCancelled, let self else { break }
                self.poll(grant: current)
            }
        }
    }

    func sceneDidResign() {
        if reading { automatic = false }
        update(supported: supported, grant: nil, reason: .ok)
    }

    func setAutomatic(_ enabled: Bool) {
        if automatic == enabled { return }
        automatic = enabled && canSend
        pendingAutomaticRevision = nil
        stopReading()
        if focusAllows(grantFocusEpoch), canSend, let grant, authority.allows(grant, direction: 1) { lastCount = readSource.changeCount() }
    }

    func setTransferNotice(_ notice: String?, grant: Grant?) {
        if self.grant == grant { transferNotice = notice }
    }

    func revision(grant: Grant, prefix: Wire.Prefix) -> Int? {
        guard focusAllows(grantFocusEpoch), self.grant == grant, authority.allows(grant, direction: 2, prefix: prefix) else { return nil }
        if let epoch = grantFocusEpoch { inboundRevision = (prefix, epoch) }
        return Self.board.changeCount
    }

    func apply(_ content: RemoteClipboardContent, revision: Int, grant: Grant, prefix: Wire.Prefix,
               completion: @escaping (Wire.Reason, Int) -> Void) {
        guard focusAllows(grantFocusEpoch), self.grant == grant, authority.allows(grant, direction: 2, prefix: prefix) else {
            completion(.staleGrant, revision)
            return
        }
        if focus != nil {
            guard let inboundRevision, inboundRevision.prefix == prefix, focusAllows(inboundRevision.epoch) else {
                completion(.staleGrant, revision)
                return
            }
            self.inboundRevision = nil
        }
        let epoch = grantFocusEpoch
        let board = Self.board
        guard board.changeCount == revision else {
            completion(.superseded, board.changeCount)
            return
        }
        var item: [String: Any] = [Self.originType: Data([1])]
        if content.format == .png { item[UTType.png.identifier] = content.bytes }
        else { item[UTType.utf8PlainText.identifier] = String(decoding: content.bytes, as: UTF8.self) }
        stopReading()
        pendingAutomaticRevision = nil
        ownWritePending = true
        board.setItems([item], options: [.localOnly: true])
        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            guard self.focusAllows(epoch) else { completion(.staleGrant, revision); return }
            self.ownWritePending = false
            guard self.grant == grant, self.authority.allows(grant, direction: 2) else {
                completion(.staleGrant, revision)
                return
            }
            let appliedRevision = board.changeCount
            guard Self.types(on: board).contains(Self.originType) else {
                completion(appliedRevision == revision ? .applyFailed : .superseded, appliedRevision)
                return
            }
            self.ownRevision = appliedRevision
            self.lastCount = appliedRevision
            completion(.ok, appliedRevision)
        }
    }

    func canPaste(_ providers: [NSItemProvider]) -> Bool {
        guard focusAllows(grantFocusEpoch), let grant, authority.allows(grant, direction: 1), providers.count == 1 else { return false }
        return Self.representation(providers[0].registeredTypeIdentifiers) != nil
    }

    func paste(_ providers: [NSItemProvider]) {
        guard canPaste(providers), let grant,
              let selected = Self.representation(providers[0].registeredTypeIdentifiers) else { return }
        let revision = readSource.changeCount()
        changed(grant, revision)
        load(providers[0], selected: selected, revision: revision, grant: grant, automatic: false)
    }

    private static var board: UIPasteboard { .general }

    private static func types(on board: UIPasteboard) -> [String] {
        board.types(forItemSet: IndexSet(integer: 0))?.first ?? []
    }

    private static func representation(_ identifiers: [String]) -> Representation? {
        guard identifiers.allSatisfy({ !blockedTypes.contains($0.lowercased()) && $0 != originType }),
              !identifiers.contains(where: { identifier in
                  guard let type = UTType(identifier) else { return false }
                  return type.conforms(to: .fileURL) || type.conforms(to: .folder)
              }) else { return nil }
        let image = identifiers.first(where: { $0 == UTType.png.identifier }) ??
            identifiers.first(where: { UTType($0)?.conforms(to: .image) == true })
        let text = identifiers.first(where: { $0 == UTType.utf8PlainText.identifier }) ??
            identifiers.first(where: { $0 == UTType.plainText.identifier })
        if let image { return Representation(identifier: image, format: .png, formats: text == nil ? 2 : 3) }
        if let text { return Representation(identifier: text, format: .text, formats: 1) }
        return nil
    }

    private func poll(grant: Grant) {
        guard focusAllows(grantFocusEpoch), self.grant == grant,
              authority.allows(grant, direction: 1) || authority.allows(grant, direction: 2) else { return }
        let count = readSource.changeCount()
        guard !ownWritePending else { return }
        if count != lastCount {
            stopReading()
            lastCount = count
            pendingAutomaticRevision = nil
            if count == ownRevision { return }
            ownRevision = nil
            if readSource.types().contains(Self.originType) { return }
            changed(grant, count)
            if automatic { pendingAutomaticRevision = count }
            return
        }
        guard automatic, pendingAutomaticRevision == count, authority.allows(grant, direction: 1) else { return }
        pendingAutomaticRevision = nil
        guard readSource.itemCount() == 1, let selected = Self.representation(readSource.types()) else { return }

        // The system enforces Paste from Other Apps permission when providers are requested.
        reading = true
        let providers = readSource.providers()
        guard providers.count == 1,
              let providerType = Self.representation(providers[0].registeredTypeIdentifiers),
              providerType.format == selected.format else {
            setAutomatic(false)
            transferNotice = "Automatic sending stopped. Use the paste button or check iPad Settings."
            return
        }
        load(providers[0], selected: providerType, revision: count, grant: grant, automatic: true)
    }

    #if targetEnvironment(simulator)
    func pollForTesting(grant: Grant) { poll(grant: grant) }
    func pollForTesting() { if let grant { poll(grant: grant) } }
    #endif

    private func stopReading() {
        readID = UUID()
        reading = false
        progress?.cancel()
        progress = nil
    }

    private func load(_ provider: NSItemProvider, selected: Representation,
                      revision: Int, grant: Grant, automatic: Bool) {
        stopReading()
        reading = true
        let id = readID
        let epoch = grantFocusEpoch
        let permit = focus?.owner.readPermit
        let worker = self.worker
        let authority = self.authority
        let limit = selected.format == .text ? 2 * grant.maxBytes : Wire.maxBytes
        let complete: (RemoteClipboardContent?, Bool) -> Void = { [weak self] content, unavailable in
            DispatchQueue.main.async {
                guard let self, self.focusAllows(epoch), self.readID == id else { return }
                self.stopReading()
                guard self.grant == grant, self.authority.allows(grant, direction: 1), !self.ownWritePending,
                      self.readSource.changeCount() == revision else { return }
                guard let content, content.bytes.count <= grant.maxBytes else {
                    if automatic && unavailable { self.setAutomatic(false) }
                    self.transferNotice = unavailable
                        ? "CouldnÃ¢â‚¬â„¢t read this copy. Check paste permission or use the paste button."
                        : "This clipboard item couldnÃ¢â‚¬â„¢t be sent."
                    return
                }
                self.send(grant, revision, content, automatic)
            }
        }
        // The provider owns this temporary URL only for the completion handler.
        progress = provider.loadFileRepresentation(forTypeIdentifier: selected.identifier) { url, _ in
            guard permit?.isValid != false, authority.allows(grant, direction: 1) else { return }
            guard let url else { complete(nil, true); return }
            let bytes: Data
            switch RemoteClipboardContent.read(url, limit: limit) {
            case .bytes(let data): bytes = data
            case .tooLarge: complete(nil, false); return
            case .unavailable: complete(nil, true); return
            }
            if !worker.submit({
                guard permit?.isValid != false, authority.allows(grant, direction: 1) else { return }
                complete(RemoteClipboardContent.prepare(bytes, format: selected.format,
                                                        formats: selected.formats, fromWire: false), false)
            }) { complete(nil, false) }
        }
    }
}

@MainActor
struct RemoteClipboardPasteButton: UIViewRepresentable {
    let pasteboard: RemoteClipboardPasteboard

    func makeUIView(context: Context) -> Target {
        Target(pasteboard: pasteboard)
    }

    func updateUIView(_ target: Target, context: Context) {
        target.pasteboard = pasteboard
    }

    final class Target: UIView {
        weak var pasteboard: RemoteClipboardPasteboard?

        init(pasteboard: RemoteClipboardPasteboard) {
            self.pasteboard = pasteboard
            super.init(frame: .zero)
            pasteConfiguration = UIPasteConfiguration(acceptableTypeIdentifiers: [
                UTType.image.identifier, UTType.plainText.identifier
            ])
            let control = UIPasteControl(configuration: UIPasteControl.Configuration())
            control.target = self
            control.accessibilityLabel = "Send clipboard to PC"
            control.translatesAutoresizingMaskIntoConstraints = false
            addSubview(control)
            NSLayoutConstraint.activate([
                control.leadingAnchor.constraint(equalTo: leadingAnchor),
                control.topAnchor.constraint(equalTo: topAnchor),
                control.bottomAnchor.constraint(equalTo: bottomAnchor),
                control.trailingAnchor.constraint(lessThanOrEqualTo: trailingAnchor),
                control.widthAnchor.constraint(greaterThanOrEqualToConstant: 44)
            ])
        }

        required init?(coder: NSCoder) { nil }

        override func canPaste(_ itemProviders: [NSItemProvider]) -> Bool {
            pasteboard?.canPaste(itemProviders) == true
        }

        override func paste(itemProviders: [NSItemProvider]) {
            pasteboard?.paste(itemProviders)
        }
    }
}
